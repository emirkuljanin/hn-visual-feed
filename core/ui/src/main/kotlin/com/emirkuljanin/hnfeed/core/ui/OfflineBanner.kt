/**
 * Shown instead of a "couldn't refresh" error while the device is offline: the cause is known, and screens retry
 * by themselves when the connection returns, so there is no retry button. Announced by TalkBack when it appears.
 */
@Composable
fun OfflineBanner(modifier: Modifier = Modifier) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .semantics { liveRegion = LiveRegionMode.Polite },
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.secondaryContainer,
            contentColor = MaterialTheme.colorScheme.onSecondaryContainer,
        ),
    ) {
        Row(
            modifier = Modifier.padding(horizontal = 16.dp, vertical = 12.dp),
            horizontalArrangement = Arrangement.spacedBy(12.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Icon(
                painter = painterResource(R.drawable.core_ui_ic_cloud_off),
                contentDescription = null,
                modifier = Modifier.size(20.dp),
            )
            Text(text = stringResource(R.string.core_ui_offline), style = MaterialTheme.typography.bodyMedium)
        }
    }
}
